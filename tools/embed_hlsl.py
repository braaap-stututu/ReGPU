# Compiles compute shaders from an HLSL file whose #include "..." directives are searched in
# the given directories (flattened first, so the compiler needs no include paths), and writes their
# SPIR-V into a C++ header as byte arrays (4-byte aligned, for vkCreateShaderModule).
# usage: embed_hlsl.py [--dxc <dxc>] <input.hlsl> <output.h> <entry>[,<entry>...] <include dir>...
# Needs DXC with SPIR-V (the Vulkan SDK's Bin/dxc: --dxc, or REGPU_DXC_EXE, else dxc on PATH). Registers are shifted as
# for ReGPU's other Vulkan shaders (src/gpu/vk/vk_shader.cpp): b 0, t 100, s 200, u 300, all in set 0.
import os
import re
import subprocess
import sys
import tempfile

args = sys.argv[1:]
dxc = os.environ.get('REGPU_DXC_EXE') or 'dxc'
if args[:1] == ['--dxc']:
    dxc, args = args[1], args[2:]
src, out, entries = args[0], args[1], args[2].split(',')
dirs = [os.path.dirname(os.path.abspath(src))] + args[3:]
seen = set()


def flatten(path):
    text = []
    for line in open(path, encoding='utf-8', errors='replace'):
        m = re.match(r'\s*#\s*include\s+"([^"]+)"', line)
        if not m:
            text.append(line)
            continue
        found = None
        for d in [os.path.dirname(path)] + dirs:
            candidate = os.path.join(d, m.group(1))
            if os.path.exists(candidate):
                found = os.path.abspath(candidate)
                break
        if not found:
            # Inside a branch for another language (ffx_core.h includes its GLSL and CPU
            # variants conditionally): if it were needed, compiling would say so.
            text.append('// embed_hlsl: not found: ' + line)
            continue
        if found in seen:  # the FidelityFX headers have include guards; once is enough
            continue
        seen.add(found)
        text.append(flatten(found))
    return ''.join(text)


with tempfile.TemporaryDirectory() as tmp:
    flat = os.path.join(tmp, 'flat.hlsl')
    with open(flat, 'w', encoding='utf-8') as f:
        f.write(flatten(src))
    blobs = {}
    for entry in entries:
        spv = os.path.join(tmp, entry + '.spv')
        r = subprocess.run([dxc, '-nologo', '-O3', '-HV', '2018', '-T', 'cs_6_0', '-E', entry, '-spirv', '-fvk-use-dx-layout',
                            '-fspv-target-env=vulkan1.2', '-fvk-b-shift', '0', '0', '-fvk-t-shift', '100', '0', '-fvk-s-shift', '200', '0',
                            '-fvk-u-shift', '300', '0', '-Fo', spv, flat], capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit('embed_hlsl: dxc failed for %s:\n%s%s' % (entry, r.stdout, r.stderr))
        blobs[entry] = open(spv, 'rb').read()

os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by tools/embed_hlsl.py from %s (SPIR-V): do not edit.\n#pragma once\n' % os.path.basename(src))
    for entry, data in blobs.items():
        f.write('alignas(4) static const unsigned char k%s[] = {\n' % entry)
        for i in range(0, len(data), 24):
            f.write(','.join(str(b) for b in data[i:i + 24]) + ',\n')
        f.write('};\n')
print('embedded %s: %s' % (out, ', '.join('%s %d bytes' % (e, len(b)) for e, b in blobs.items())))
